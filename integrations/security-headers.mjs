/**
 * Astro integration: after every build, hash all inline <script> blocks in the generated HTML
 * and write dist/_headers (Cloudflare Pages format) with a strict Content-Security-Policy and
 * hardened security headers. No inline JS can run unless it is one of OUR hashed scripts.
 */
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** @param {string} dir @returns {Promise<string[]>} */
async function htmlFiles(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...(await htmlFiles(p)));
    else if (e.name.endsWith('.html')) out.push(p);
  }
  return out;
}

/**
 * @param {{ connect?: string[], scripts?: string[], frames?: string[], images?: string[] }} [opts]
 * @returns {import('astro').AstroIntegration}
 */
export default function securityHeaders(opts = {}) {
  const { connect = [], scripts = [], frames = [], images = [] } = opts;
  return {
    name: 'periodicfit-security-headers',
    hooks: {
      'astro:build:done': async ({ dir, logger }) => {
        const root = fileURLToPath(dir);
        const hashes = new Set();
        for (const file of await htmlFiles(root)) {
          const html = await readFile(file, 'utf8');
          for (const m of html.matchAll(/<script(?![^>]*\bsrc=)([^>]*)>([\s\S]*?)<\/script>/g)) {
            const attrs = m[1];
            const type = /type="([^"]+)"/.exec(attrs)?.[1];
            if (type && !['module', 'text/javascript', 'application/javascript'].includes(type)) continue; // JSON / data blocks are never executed
            hashes.add(`'sha256-${createHash('sha256').update(m[2]).digest('base64')}'`);
          }
        }
        const csp = [
          "default-src 'self'",
          `script-src 'self' ${[...hashes].join(' ')} ${scripts.join(' ')}`.trim(),
          "style-src 'self' 'unsafe-inline'",           // inline style attributes are used for layout
          `img-src 'self' data: blob: ${images.join(' ')}`.trim(),
          "font-src 'self'",
          `connect-src 'self' ${connect.join(' ')}`.trim(),
          `frame-src ${frames.length ? frames.join(' ') : "'none'"}`,
          "form-action 'self' " + connect.join(' '),
          "base-uri 'self'",
          "object-src 'none'",
          "frame-ancestors 'none'",
          'upgrade-insecure-requests',
        ].join('; ');
        const headers = `# Generated by integrations/security-headers.mjs on build. Do not edit by hand.
/*
  Content-Security-Policy: ${csp}
  Strict-Transport-Security: max-age=63072000; includeSubDomains; preload
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), magnetometer=(), gyroscope=(), accelerometer=(), browsing-topics=()
  Cross-Origin-Opener-Policy: same-origin
  Cross-Origin-Resource-Policy: same-origin
  X-Permitted-Cross-Domain-Policies: none
  X-DNS-Prefetch-Control: off

/_astro/*
  Cache-Control: public, max-age=31536000, immutable
`;
        await writeFile(join(root, '_headers'), headers);
        logger.info(`_headers written (${hashes.size} inline script hash${hashes.size === 1 ? '' : 'es'})`);
      },
    },
  };
}
